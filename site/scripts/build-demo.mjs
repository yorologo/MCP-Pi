import fs from "node:fs";
import { createHash } from "node:crypto";

const source = new URL("../../mcp-adapter/testdata/contracts/policy_cases.json", import.meta.url);
const output = new URL("../assets/js/demo-scenarios.js", import.meta.url);
const bytes = fs.readFileSync(source);
const contracts = JSON.parse(bytes);
// The Go policy tests exercise these same cases against a temporary Registry.
const cases = [
  ["read_authorized", "authorization_cases", "read_allowed", "Lectura con permiso", "Read with a grant"],
  ["anonymous_denied", "authorization_cases", "anonymous_denied", "Identidad ausente", "Missing identity"],
  ["unknown_tool", "authorization_cases", "unknown_tool_before_registry_state", "Herramienta desconocida", "Unknown tool"],
  ["missing_grant", "authorization_cases", "grant_precedes_write_switch", "Permiso de escritura ausente", "Missing write grant"],
  ["writes_disabled_killswitch", "authorization_cases", "writes_global_kill_switch", "Escrituras deshabilitadas", "Writes disabled"],
  ["target_shell_disabled", "authorization_cases", "shell_kill_switch", "Shell deshabilitada", "Shell disabled"],
  ["privilege_denied_target_admin", "privilege_cases", "wildcard_does_not_grant_target_admin", "El comodín no concede target_admin", "Wildcard does not grant target_admin"],
  ["privilege_authorized", "privilege_cases", "explicit_target_admin", "Comprobación de grant target_admin", "Checking the target_admin grant"],
  ["health_killswitch_exception", "authorization_cases", "gateway_disabled_health_exception", "Health con gateway deshabilitado", "Health with gateway disabled"],
];
const scenarios = cases.map(([id, group, name, es, en]) => {
  const input = contracts[group].find(c => c.name === name);
  if (!input) throw new Error(`Missing canonical case: ${name}`);
  const privilege = group === "privilege_cases";
  const noteEs = privilege
    ? "Comprueba solo el grant target_admin. La ejecución también exige autorización ordinaria, política del destino, aprobación aplicable y backend verificado."
    : "Comprueba autorización interna en Policy.AuthorizeClient; no verifica aquí rutas, SSH, ejecución ni persistencia de auditoría. Core.Invoke puede devolver un código público diferente.";
  const noteEn = privilege
    ? "Checks only the target_admin grant. Execution also requires ordinary authorization, target policy, applicable approval and a verified backend."
    : "Checks internal authorization in Policy.AuthorizeClient; paths, SSH, execution and audit persistence are not checked here. Core.Invoke may return a different public code.";
  return {
    id, contract_group: group, contract_case: name,
    title_es: es, title_en: en,
    description_es: noteEs, description_en: noteEn,
    request: input,
    decision: { allowed: input.allowed, code: input.error_code,
      reason_es: input.allowed ? "Comprobación interna permitida; no demuestra ejecución." : "Comprobación interna denegada. " + input.reason,
      reason_en: input.allowed ? "Internal check allowed; execution is not demonstrated." : input.reason },
    trace: [{ passed: input.allowed, note_es: noteEs, note_en: noteEn }],
    audit_record: { simulated: true, persisted: false, contract_case: name,
      allowed: input.allowed, policy_code: input.error_code,
      note: "Educational summary, not a gateway Activity record or MCP response." },
  };
});
const provenance = { schema: contracts.schema,
  source: "mcp-adapter/testdata/contracts/policy_cases.json",
  source_sha256: createHash("sha256").update(bytes).digest("hex"),
  verification: "go test -count=1 ./internal/policy -run 'Test(Authorization|PrivilegeAuthorization)MatchesFrozenPythonPolicy'" };
const result = `// Generated by site/scripts/build-demo.mjs. Do not edit.\nconst DEMO_PROVENANCE = ${JSON.stringify(provenance, null, 2)};\nconst DEMO_SCENARIOS = ${JSON.stringify(scenarios, null, 2)};\nif (typeof module !== "undefined") module.exports = { DEMO_SCENARIOS, DEMO_PROVENANCE };\n`;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(output, "utf8") !== result) throw new Error("Demo is stale: run node site/scripts/build-demo.mjs");
} else {
  fs.writeFileSync(output, result);
}
